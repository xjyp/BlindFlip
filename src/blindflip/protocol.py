"""Pairwise judge prompt and verdict parser."""
import os
from dataclasses import dataclass

JUDGE_SYSTEM_PROMPT = 'You are a helpful assistant in evaluating the quality of the two responses according to the original task. Your goal is to select the best output for the original task.  Select the Output (a) or Output (b) that is better for the given instruction. The two outputs are generated by two different AI chatbots respectively.\nDo NOT provide any explanation for your choice.\nDo NOT say both / neither are good.'

@dataclass
class PairwiseExample:
    question_id: str
    instruction: str
    response_a: str
    response_b: str
    source_note: str = ''

def build_judge_user_prompt(example: PairwiseExample) -> str:
    note = example.source_note if example.source_note is not None else ''
    note_block = note if note else '(empty)'
    note_label = os.environ.get('BLINDFLIP_NOTE_LABEL', 'Source Note')
    return f'You are a helpful assistant in evaluating the quality of the outputs for a given instruction. Your goal is to select the best output for the given instruction.\nSelect the Output (a) or Output (b) that is better for the given instruction. The two outputs are generated by two different AI chatbots respectively.\nDo NOT provide any explanation for your choice.\nDo NOT say both / neither are good.\nYou should answer using ONLY "Output (a)" or "Output (b)". Do NOT output any other words.\n# Instruction:\n{example.instruction}\n# Output (a):\n{example.response_a}\n# Output (b):\n{example.response_b}\n# Which is better, Output (a) or Output (b)? Your response should be either "Output (a)" or "Output (b)":\n[{note_label}]\n{note_block}'

def parse(raw):
    if not raw:
        return None
    t = raw.strip()
    import json as _json
    try:
        obj = _json.loads(t)
        if isinstance(obj, dict):
            choice = obj.get('choice')
            if isinstance(choice, str):
                c = choice.strip().upper()
                if c.startswith('A'):
                    return 0
                if c.startswith('B'):
                    return 1
    except Exception:
        pass
    if '{' in t and '}' in t:
        try:
            start = t.index('{')
            end = t.rindex('}') + 1
            obj = _json.loads(t[start:end])
            if isinstance(obj, dict):
                choice = obj.get('choice')
                if isinstance(choice, str):
                    c = choice.strip().upper()
                    if c.startswith('A'):
                        return 0
                    if c.startswith('B'):
                        return 1
        except Exception:
            pass
    low = t.lower()
    if low.startswith('output (a)') or low == 'a' or low == '(a)':
        return 0
    if low.startswith('output (b)') or low == 'b' or low == '(b)':
        return 1
    toks = t.split()
    if toks:
        for cand in (toks[0], toks[-1]):
            c = cand.lower().strip('.,:;()')
            if c in ('a', 'output (a)'):
                return 0
            if c in ('b', 'output (b)'):
                return 1
    return None
